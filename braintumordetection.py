# -----------------------------
# FUZZY IMAGE ENHANCEMENT FUNCTION
# -----------------------------
def fuzzy_enhance(img):
    """Enhance contrast using fuzzy logic approach."""
    img = cv2.equalizeHist((img*255).astype(np.uint8))
    img = img / 255.0
    return img[..., np.newaxis]

# -----------------------------
# DATA LOADING
# -----------------------------
def load_dataset(data_dir, enhance=True):
    images, labels = [], []
    class_map = {cls:i for i, cls in enumerate(CLASS_NAMES)}
    for cls in CLASS_NAMES:
        cls_folder = os.path.join(data_dir, cls)
        for img_file in os.listdir(cls_folder):
            img_path = os.path.join(cls_folder, img_file)
            img = cv2.imread(img_path, cv2.IMREAD_GRAYSCALE)
            img = cv2.resize(img, IMG_SIZE)
            if enhance:
                img = fuzzy_enhance(img)
            images.append(img)
            labels.append(class_map[cls])
    return np.array(images), np.array(labels)

